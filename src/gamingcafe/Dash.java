    private void tableStyle(JTable table, JScrollPane scrollPane) {
        // 1. Table Main Colors
        table.setBackground(java.awt.Color.decode("#162244"));
        table.setForeground(java.awt.Color.WHITE);
        table.setSelectionBackground(java.awt.Color.decode("#0466c8")); // Active row color
        table.setSelectionForeground(java.awt.Color.WHITE);

        // 2. Grid & Layout
        table.setRowHeight(35);
        table.setShowVerticalLines(false);
        table.setGridColor(java.awt.Color.decode("#2A3B69"));

        // 3. Table Header
        javax.swing.table.JTableHeader header = table.getTableHeader();
        header.setBackground(java.awt.Color.decode("#0B132B"));
        header.setForeground(java.awt.Color.WHITE);
        header.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 14));
        header.setBorder(javax.swing.BorderFactory.createMatteBorder(0, 0, 2, 0, java.awt.Color.decode("#0466c8")));

        // 4. ScrollPane
        if (scrollPane != null) {
            scrollPane.setBackground(java.awt.Color.decode("#162244"));
            scrollPane.getViewport().setBackground(java.awt.Color.decode("#162244"));
            scrollPane.setBorder(javax.swing.BorderFactory.createEmptyBorder());
        }
        table.setFont(new Font("Segoe UI", Font.PLAIN, 14));
        // 6. Text Alignment
        DefaultTableCellRenderer centerRenderer = new DefaultTableCellRenderer();
        centerRenderer.setHorizontalAlignment(JLabel.CENTER);

        // Table columns 
        for (int i = 0; i < table.getColumnModel().getColumnCount(); i++) {
            table.getColumnModel().getColumn(i).setCellRenderer(centerRenderer);
        }

    }

    private void loadUserTable() {

        try {
            DefaultTableModel dt = (DefaultTableModel) tableUser.getModel();
            dt.setRowCount(0);

            pst = db.con.prepareStatement("SELECT emp_no, f_name, l_name, nic, username, email, phone, role FROM user");
            rs = pst.executeQuery();

            while (rs.next()) {
                Vector v = new Vector();

                v.add(rs.getString("emp_no"));
                v.add(rs.getString("f_name") + " " + rs.getString("l_name"));
                v.add(rs.getString("username"));
                v.add(rs.getString("nic"));
                v.add(rs.getString("email"));
                v.add(rs.getString("phone"));
                v.add(rs.getString("role"));

                dt.addRow(v);
            }
            pst.close();
            rs.close();

        } catch (Exception e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Table load error: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

    private void generatePcId(String category) {
        try {
            Random randpc = new Random();
            boolean isUnique = false;
            String newPcId = "";

            while (!isUnique) {

                int randmNum = randpc.nextInt(9000) + 1000;
                newPcId = category + "-GG-" + randmNum;

                pst = db.con.prepareStatement("SELECT pc_id FROM pc_table WHERE pc_id = ?");
                pst.setString(1, newPcId);
                rs = pst.executeQuery();

                if (!rs.next()) {
                    isUnique = true;
                }

                pst.close();
                rs.close();

                txtPcId.setText(newPcId);
            }
        } catch (SQLException ex) {
            System.getLogger(Dash.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }

    }

